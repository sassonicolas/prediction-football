import streamlit as st
import numpy as np

# 1. TITOLO DEL SITO WEB
st.title("⚽ Il Mio Predittore di Risultati IA")
st.write("Inserisci i dati delle squadre e simula il match!")

# 2. INTERFACCIA UTENTE (I menu del sito)
col1, col2 = st.columns(2)

with col1:
    squadra_casa = st.text_input("Squadra in Casa", "Spagna")
    gol_fatti_casa = st.slider(f"Media Gol Fatti {squadra_casa}", 0.0, 5.0, 2.1)
    gol_subiti_casa = st.slider(f"Media Gol Subiti {squadra_casa}", 0.0, 5.0, 0.5)

with col2:
    squadra_ospite = st.text_input("Squadra Ospite", "Belgio")
    gol_fatti_ospite = st.slider(f"Media Gol Fatti {squadra_ospite}", 0.0, 5.0, 1.8)
    gol_subiti_ospite = st.slider(f"Media Gol Subiti {squadra_ospite}", 0.0, 5.0, 1.2)

# 3. IL BOTTONE PER AVVIARE LA SIMULAZIONE
if st.button("🔥 SIMULA PARTITA"):

    # Calcolo dei gol attesi (xG)
    lambda_casa = gol_fatti_casa * (gol_subiti_ospite / 1.0)
    lambda_ospite = gol_fatti_ospite * (gol_subiti_casa / 1.0)

    # 100.000 simulazioni istantanee
    simulazioni = 100000
    gol_casa_simulati = np.random.poisson(lambda_casa, simulazioni)
    gol_ospite_simulati = np.random.poisson(lambda_ospite, simulazioni)

    risultati = {}
    for i in range(simulazioni):
        ris = f"{gol_casa_simulati[i]} - {gol_ospite_simulati[i]}"
        risultati[ris] = risultati.get(ris, 0) + 1

    risultati_ordinati = sorted(risultati.items(), key=lambda x: x[1], reverse=True)

    # 4. MOSTRIAMO I RISULTATI SUL SITO
    st.subheader("📊 Top 3 Risultati Esatti Più Probabili")
    for ris, conteggio in risultati_ordinati[:3]:
        prob = (conteggio / simulazioni) * 100
        st.write(f"**{ris}** con il **{prob:.2f}%** di probabilità")